const dicts: Record<Lang, Dict> = { nl, en };

/** The texts for the current language. Reading it inside a component keeps it reactive. */
export function tr(): Dict {
  return dicts[settings.lang];
}

/** Fills in {placeholders}. */
export function fmt(text: string, values: Record<string, string | number>): string {
  return text.replace(/\{(\w+)\}/g, (_, k) => String(values[k] ?? ''));
}

/** A place's name in the current language. */
export function itemName(item: Item, lang: Lang = settings.lang): string {
  return lang === 'en' ? (item.en ?? item.nl) : item.nl;
}

export function packName(p: { nl: string; en: string }, lang: Lang = settings.lang): string {
  return p[lang];
}
